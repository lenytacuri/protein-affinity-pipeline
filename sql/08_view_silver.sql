USE ROLE PPA_PIPELINE;
USE WAREHOUSE PPA_WH;
SELECT OBSERVATION_ID,PDB_ID,SOURCE_DATASET,KD_M,PKD,TEMPERATURE_RAW,TEMPERATURE_K,
       TEMPERATURE_STATUS,GEOMETRY_STATUS,MUTATION_STRUCTURE_STATUS,GEOMETRY_ID
FROM PROTEIN_AFFINITY.SILVER.AFFINITY_OBSERVATIONS
ORDER BY SOURCE_SHA256,SOURCE_ROW LIMIT 50;

-- Ver seleccion adaptativa de una geometria concreta del complejo 1A22.
WITH example AS (
 SELECT GEOMETRY_ID FROM PROTEIN_AFFINITY.SILVER.STRUCTURE_GEOMETRY
 WHERE PDB_ID='1A22' ORDER BY GEOMETRY_ID LIMIT 1
)
SELECT PARTNER,CHAIN_ID,RESIDUE_NUMBER,INSERTION_CODE,RESIDUE_NAME,
       MIN_DISTANCE_ANGSTROM,Q1_THRESHOLD_ANGSTROM,SELECTED_Q1,WITHIN_10
FROM PROTEIN_AFFINITY.SILVER.INTERFACE_RESIDUES
WHERE GEOMETRY_ID IN (SELECT GEOMETRY_ID FROM example)
ORDER BY PARTNER,CHAIN_ID,RESIDUE_NUMBER,INSERTION_CODE;
