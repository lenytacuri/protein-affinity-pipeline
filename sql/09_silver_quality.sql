USE ROLE PPA_PIPELINE;
USE WAREHOUSE PPA_WH;

-- No confundir numero de geometrias con numero de observaciones experimentales.
SELECT GEOMETRY_STATUS,COUNT(*) AS OBSERVATIONS
FROM PROTEIN_AFFINITY.SILVER.AFFINITY_OBSERVATIONS GROUP BY 1 ORDER BY 2 DESC;
SELECT GEOMETRY_STATUS,ISSUE,COUNT(*) AS GEOMETRIES
FROM PROTEIN_AFFINITY.SILVER.STRUCTURE_GEOMETRY GROUP BY 1,2 ORDER BY 3 DESC;
SELECT MUTATION_STRUCTURE_STATUS,COUNT(*) AS OBSERVATIONS
FROM PROTEIN_AFFINITY.SILVER.AFFINITY_OBSERVATIONS GROUP BY 1 ORDER BY 2 DESC;
SELECT TEMPERATURE_STATUS,COUNT(*) AS OBSERVATIONS
FROM PROTEIN_AFFINITY.SILVER.AFFINITY_OBSERVATIONS GROUP BY 1 ORDER BY 2 DESC;

-- Residuo origen y destino de cada par conservado, con sus cadenas.
SELECT g.PDB_ID,l.CHAIN_ID AS LIGAND_CHAIN,l.RESIDUE_NUMBER AS LIGAND_NUMBER,
       l.INSERTION_CODE AS LIGAND_INSERTION,l.RESIDUE_NAME AS LIGAND_RESIDUE,
       r.CHAIN_ID AS RECEPTOR_CHAIN,r.RESIDUE_NUMBER AS RECEPTOR_NUMBER,
       r.INSERTION_CODE AS RECEPTOR_INSERTION,r.RESIDUE_NAME AS RECEPTOR_RESIDUE,
       p.DISTANCE_ANGSTROM
FROM PROTEIN_AFFINITY.SILVER.RESIDUE_PAIRS p
JOIN PROTEIN_AFFINITY.SILVER.INTERFACE_RESIDUES l ON p.LIGAND_RESIDUE_ID=l.RESIDUE_ID
JOIN PROTEIN_AFFINITY.SILVER.INTERFACE_RESIDUES r ON p.RECEPTOR_RESIDUE_ID=r.RESIDUE_ID
JOIN PROTEIN_AFFINITY.SILVER.STRUCTURE_GEOMETRY g ON p.GEOMETRY_ID=g.GEOMETRY_ID
WHERE g.PDB_ID='1A22'
ORDER BY p.DISTANCE_ANGSTROM LIMIT 50;
