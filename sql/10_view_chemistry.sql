USE ROLE PPA_PIPELINE;
USE WAREHOUSE PPA_WH;

SELECT PDB_ID,GEOMETRY_ID,PARTNER,CHEMISTRY_STATUS,N_SELECTED,N_SUPPORTED,
       PROPERTY_COVERAGE,FRACTION_NONPOLAR,FRACTION_POLAR_UNCHARGED,
       FRACTION_ACIDIC,FRACTION_BASIC,FRACTION_AROMATIC_RING,
       FRACTION_SULFUR_CONTAINING,MEAN_KD_HYDROPATHY,AA_ENTROPY_BITS
FROM PROTEIN_AFFINITY.SILVER.INTERFACE_CHEMISTRY
ORDER BY PDB_ID,GEOMETRY_ID,PARTNER LIMIT 100;

-- Unir por separado L y R mantiene una fila por observacion experimental.
SELECT o.OBSERVATION_ID,o.PDB_ID,o.PKD,o.MUTATION_STRUCTURE_STATUS,
       l.CHEMISTRY_STATUS AS LIGAND_CHEMISTRY_STATUS,
       r.CHEMISTRY_STATUS AS RECEPTOR_CHEMISTRY_STATUS,
       l.FRACTION_NONPOLAR AS LIGAND_FRACTION_NONPOLAR,
       r.FRACTION_NONPOLAR AS RECEPTOR_FRACTION_NONPOLAR,
       l.MEAN_KD_HYDROPATHY AS LIGAND_MEAN_HYDROPATHY,
       r.MEAN_KD_HYDROPATHY AS RECEPTOR_MEAN_HYDROPATHY
FROM PROTEIN_AFFINITY.SILVER.AFFINITY_OBSERVATIONS o
LEFT JOIN PROTEIN_AFFINITY.SILVER.INTERFACE_CHEMISTRY l
 ON o.GEOMETRY_ID=l.GEOMETRY_ID AND l.PARTNER='L'
LEFT JOIN PROTEIN_AFFINITY.SILVER.INTERFACE_CHEMISTRY r
 ON o.GEOMETRY_ID=r.GEOMETRY_ID AND r.PARTNER='R'
ORDER BY o.SOURCE_SHA256,o.SOURCE_ROW LIMIT 100;
