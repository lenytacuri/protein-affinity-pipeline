-- Ejecutar una vez en una hoja SQL de Snowflake con acceso de administrador.
-- Reejecutable: no borra ni reemplaza bases, tablas o datos existentes.
USE ROLE SYSADMIN;

CREATE WAREHOUSE IF NOT EXISTS PPA_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  COMMENT = 'PSet 2: ingesta, dbt y OBT de afinidad proteina-proteina';

CREATE DATABASE IF NOT EXISTS PROTEIN_AFFINITY;
CREATE SCHEMA IF NOT EXISTS PROTEIN_AFFINITY.RAW;
CREATE SCHEMA IF NOT EXISTS PROTEIN_AFFINITY.BRONZE;
CREATE SCHEMA IF NOT EXISTS PROTEIN_AFFINITY.SILVER;
CREATE SCHEMA IF NOT EXISTS PROTEIN_AFFINITY.GOLD;
CREATE SCHEMA IF NOT EXISTS PROTEIN_AFFINITY.ANALYTICS;

-- El pipeline tendra permisos en su base de trabajo, no ACCOUNTADMIN.
USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS PPA_PIPELINE;
GRANT ROLE PPA_PIPELINE TO ROLE SYSADMIN;
GRANT USAGE ON WAREHOUSE PPA_WH TO ROLE PPA_PIPELINE;
GRANT USAGE ON DATABASE PROTEIN_AFFINITY TO ROLE PPA_PIPELINE;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE STAGE, CREATE FILE FORMAT
  ON ALL SCHEMAS IN DATABASE PROTEIN_AFFINITY TO ROLE PPA_PIPELINE;

-- Comprobacion: deben aparecer las cinco capas y el warehouse suspendido.
USE ROLE SYSADMIN;
SHOW SCHEMAS IN DATABASE PROTEIN_AFFINITY;
SHOW WAREHOUSES LIKE 'PPA_WH';
