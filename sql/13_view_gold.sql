-- Shape de las cinco tablas Gold.
SELECT t.TABLE_NAME,t.ROW_COUNT AS FILAS,COUNT(c.COLUMN_NAME) AS COLUMNAS
FROM PROTEIN_AFFINITY.INFORMATION_SCHEMA.TABLES t
JOIN PROTEIN_AFFINITY.INFORMATION_SCHEMA.COLUMNS c
 ON t.TABLE_CATALOG=c.TABLE_CATALOG AND t.TABLE_SCHEMA=c.TABLE_SCHEMA AND t.TABLE_NAME=c.TABLE_NAME
WHERE t.TABLE_SCHEMA='GOLD' AND t.TABLE_TYPE='BASE TABLE'
GROUP BY t.TABLE_NAME,t.ROW_COUNT ORDER BY t.TABLE_NAME;

-- Ejemplo de la futura OBT, consultado en SQL (todavia no es Spark).
SELECT f.OBSERVATION_ID,f.PDB_ID,f.PKD,s.SOURCE_DATASET,e.TEMPERATURE_K,e.AFFINITY_METHOD,
       f.GEOMETRY_STATUS,f.MUTATION_STRUCTURE_STATUS,
       g.MIN_DISTANCE_ANGSTROM,
       l.CHEM_MEAN_KD_HYDROPATHY AS LIGAND_HYDROPATHY,
       r.CHEM_MEAN_KD_HYDROPATHY AS RECEPTOR_HYDROPATHY,
       l.BACKBONE_PHI_MEAN_SIN AS LIGAND_PHI_MEAN_SIN,
       r.BACKBONE_PHI_MEAN_SIN AS RECEPTOR_PHI_MEAN_SIN
FROM PROTEIN_AFFINITY.GOLD.FACT_AFFINITY f
LEFT JOIN PROTEIN_AFFINITY.GOLD.DIM_SOURCE s USING(SOURCE_KEY)
LEFT JOIN PROTEIN_AFFINITY.GOLD.DIM_EXPERIMENT e USING(EXPERIMENT_KEY)
LEFT JOIN PROTEIN_AFFINITY.GOLD.DIM_GEOMETRY g ON f.GEOMETRY_ID=g.GEOMETRY_ID
LEFT JOIN PROTEIN_AFFINITY.GOLD.DIM_PARTICIPANT_FEATURES l ON f.LIGAND_PARTICIPANT_KEY=l.PARTICIPANT_KEY
LEFT JOIN PROTEIN_AFFINITY.GOLD.DIM_PARTICIPANT_FEATURES r ON f.RECEPTOR_PARTICIPANT_KEY=r.PARTICIPANT_KEY
ORDER BY f.OBSERVATION_ID LIMIT 100;

SELECT GEOMETRY_STATUS,MUTATION_STRUCTURE_STATUS,COUNT(*) AS OBSERVACIONES
FROM PROTEIN_AFFINITY.GOLD.FACT_AFFINITY GROUP BY 1,2 ORDER BY 1,2;
