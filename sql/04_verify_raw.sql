-- Ejecutar despues de load_raw.py. Solo consultas.
USE ROLE PPA_PIPELINE;
USE WAREHOUSE PPA_WH;
USE DATABASE PROTEIN_AFFINITY;

-- Una fila original no es lo mismo que un codigo PDB.
SELECT COUNT(*) AS FILAS_ORIGINALES,
       COUNT(DISTINCT RECORD_ID) AS CLAVES_UNICAS,
       COUNT(DISTINCT PDB_ID) AS PDB_DISTINTOS
FROM RAW.SOURCE_RECORDS
WHERE INPUT_KIND = 'measurement_table';

SELECT RAW_RECORD:payload:"Source Data Set"::VARCHAR AS FUENTE,
       COUNT(*) AS FILAS
FROM RAW.SOURCE_RECORDS
GROUP BY 1 ORDER BY 1;

-- Repetir PDB es esperado. Estas son distintas filas del Excel.
SELECT PDB_ID, COUNT(*) AS FILAS_DEL_EXCEL
FROM RAW.SOURCE_RECORDS
GROUP BY 1 HAVING COUNT(*) > 1
ORDER BY 2 DESC LIMIT 10;

SELECT BATCH_ID, STATUS, SOURCE_SHA256,
       EXTRACTION_SUMMARY:status::VARCHAR AS COBERTURA_EXTRACCION,
       LOADED_AT
FROM RAW.INGESTION_BATCHES ORDER BY LOADED_AT;

-- 404 conservados como incidencias; no se borran las mediciones asociadas.
SELECT PDB_ID, RESOURCE, RECEIPT:status::VARCHAR AS ESTADO,
       RECEIPT:http_status::NUMBER AS HTTP
FROM RAW.BATCH_RESOURCES
WHERE RECEIPT:status::VARCHAR NOT IN ('cached', 'downloaded')
ORDER BY BATCH_ID, PDB_ID, RESOURCE;

SELECT COUNT(*) AS METADATOS_RCSB FROM RAW.RCSB_ENTRIES;
SELECT COUNT(*) AS ARCHIVOS_RCSB FROM RAW.RESOURCE_FILES;
