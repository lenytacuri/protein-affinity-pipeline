-- Se ejecuta con PPA_PIPELINE en PROTEIN_AFFINITY. No elimina ni reemplaza datos.
CREATE STAGE IF NOT EXISTS RAW.SOURCE_FILES;
CREATE TABLE IF NOT EXISTS RAW.SOURCE_RECORDS (
    RECORD_ID VARCHAR NOT NULL,
    SOURCE_SHA256 VARCHAR NOT NULL,
    PDB_ID VARCHAR,
    INPUT_KIND VARCHAR NOT NULL,
    RAW_RECORD VARIANT NOT NULL,
    LOADED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);
CREATE TABLE IF NOT EXISTS RAW.RCSB_ENTRIES (
    CONTENT_SHA256 VARCHAR NOT NULL,
    PDB_ID VARCHAR NOT NULL,
    PAYLOAD VARIANT NOT NULL,
    LOADED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);
CREATE TABLE IF NOT EXISTS RAW.RESOURCE_FILES (
    CONTENT_SHA256 VARCHAR NOT NULL,
    STAGE_PATH VARCHAR NOT NULL,
    BYTE_COUNT NUMBER NOT NULL,
    LOADED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);
CREATE TABLE IF NOT EXISTS RAW.BATCH_RESOURCES (
    BATCH_ID VARCHAR NOT NULL,
    PDB_ID VARCHAR NOT NULL,
    RESOURCE VARCHAR NOT NULL,
    RECEIPT VARIANT NOT NULL,
    LOADED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);
CREATE TABLE IF NOT EXISTS RAW.INGESTION_BATCHES (
    BATCH_ID VARCHAR NOT NULL,
    BATCH_SHA256 VARCHAR NOT NULL,
    SOURCE_SHA256 VARCHAR NOT NULL,
    STAGE_PREFIX VARCHAR NOT NULL,
    EXTRACTION_SUMMARY VARIANT NOT NULL,
    STATUS VARCHAR NOT NULL,
    LOADED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);
