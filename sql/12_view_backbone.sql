USE ROLE PPA_PIPELINE;
USE WAREHOUSE PPA_WH;

-- Resumen por participante, listo para unir a la OBT.
SELECT PDB_ID,GEOMETRY_ID,PARTNER,BACKBONE_STATUS,N_SELECTED,
       N_PHI_PSI_COMPLETE,FRACTION_PHI_PSI_COMPLETE,
       PHI_MEAN_SIN,PHI_MEAN_COS,PHI_CIRCULAR_VARIANCE,
       PSI_MEAN_SIN,PSI_MEAN_COS,PSI_CIRCULAR_VARIANCE,
       OMEGA_MEAN_SIN,OMEGA_MEAN_COS,OMEGA_CIRCULAR_VARIANCE,
       TAU_DEG_MEAN,TAU_DEG_STD_POP,N_CA_LENGTH_MEAN,CA_C_LENGTH_MEAN,PEPTIDE_CN_LENGTH_MEAN
FROM PROTEIN_AFFINITY.SILVER.BACKBONE_FEATURES
ORDER BY PDB_ID,GEOMETRY_ID,PARTNER LIMIT 100;

-- Mediciones de cada residuo seleccionado de un ejemplo.
SELECT g.PDB_ID,b.PARTNER,b.CHAIN_ID,b.RESIDUE_NUMBER,b.INSERTION_CODE,b.RESIDUE_NAME,
       b.PHI_DEG,b.PSI_DEG,b.OMEGA_DEG,b.TAU_DEG,
       b.PHI_STATUS,b.PSI_STATUS,b.OMEGA_STATUS
FROM PROTEIN_AFFINITY.SILVER.BACKBONE_RESIDUES b
JOIN PROTEIN_AFFINITY.SILVER.STRUCTURE_GEOMETRY g USING(GEOMETRY_ID)
WHERE g.PDB_ID='1A22'
ORDER BY b.GEOMETRY_ID,b.PARTNER,b.RESIDUE_NUMBER,b.INSERTION_CODE;

-- Mantiene una fila por observacion experimental.
SELECT o.OBSERVATION_ID,o.PDB_ID,o.PKD,o.MUTATION_STRUCTURE_STATUS,
       l.PHI_MEAN_SIN AS LIGAND_PHI_MEAN_SIN,l.PHI_MEAN_COS AS LIGAND_PHI_MEAN_COS,
       r.PHI_MEAN_SIN AS RECEPTOR_PHI_MEAN_SIN,r.PHI_MEAN_COS AS RECEPTOR_PHI_MEAN_COS,
       l.FRACTION_PHI_PSI_COMPLETE AS LIGAND_ANGLE_COVERAGE,
       r.FRACTION_PHI_PSI_COMPLETE AS RECEPTOR_ANGLE_COVERAGE
FROM PROTEIN_AFFINITY.SILVER.AFFINITY_OBSERVATIONS o
LEFT JOIN PROTEIN_AFFINITY.SILVER.BACKBONE_FEATURES l ON o.GEOMETRY_ID=l.GEOMETRY_ID AND l.PARTNER='L'
LEFT JOIN PROTEIN_AFFINITY.SILVER.BACKBONE_FEATURES r ON o.GEOMETRY_ID=r.GEOMETRY_ID AND r.PARTNER='R'
ORDER BY o.SOURCE_SHA256,o.SOURCE_ROW LIMIT 100;
