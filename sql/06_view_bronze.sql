USE ROLE PPA_PIPELINE;
USE WAREHOUSE PPA_WH;

-- Cada observacion del Excel aparece como una fila con columnas legibles.
SELECT OBSERVATION_ID, SOURCE_DATASET, COMPLEX_ID, PDB_ID,
       LIGAND_CHAINS_RAW, RECEPTOR_CHAINS_RAW, MUTATIONS_RAW,
       KD_M, TEMPERATURE_RAW, AFFINITY_METHOD_RAW, AFFINITY_REFERENCE_RAW
FROM PROTEIN_AFFINITY.BRONZE.AFFINITY_OBSERVATIONS
ORDER BY SOURCE_SHA256, SOURCE_ROW
LIMIT 50;

-- Verificar el universo completo, no solo la muestra de 50 filas.
SELECT COUNT(*) AS OBSERVACIONES,
       COUNT(DISTINCT OBSERVATION_ID) AS CLAVES_UNICAS,
       COUNT(DISTINCT PDB_ID) AS PDB_DISTINTOS
FROM PROTEIN_AFFINITY.BRONZE.AFFINITY_OBSERVATIONS;
