USE ROLE PPA_PIPELINE;
USE WAREHOUSE PPA_WH;

-- Shape real: cuenta las filas y consulta la cantidad de columnas.
SELECT COUNT(*) AS FILAS,
       (SELECT COUNT(*) FROM PROTEIN_AFFINITY.INFORMATION_SCHEMA.COLUMNS
        WHERE TABLE_SCHEMA='ANALYTICS' AND TABLE_NAME='OBT_AFFINITY') AS COLUMNAS
FROM PROTEIN_AFFINITY.ANALYTICS.OBT_AFFINITY;

-- Ejemplo: una fila por observacion, con ambas mitades del complejo.
SELECT OBSERVATION_ID,PDB_ID,PKD,SOURCE_DATASET,TEMPERATURE_K,
       GEOMETRY_STATUS,MUTATION_STRUCTURE_STATUS,
       LIGAND_CHEM_MEAN_KD_HYDROPATHY,RECEPTOR_CHEM_MEAN_KD_HYDROPATHY,
       LIGAND_BACKBONE_PHI_MEAN_SIN,RECEPTOR_BACKBONE_PHI_MEAN_SIN
FROM PROTEIN_AFFINITY.ANALYTICS.OBT_AFFINITY
ORDER BY OBSERVATION_ID LIMIT 100;

SELECT COUNT(*) AS FILAS,COUNT(DISTINCT OBSERVATION_ID) AS IDS_UNICOS,
       COUNT_IF(GEOMETRY_ID IS NULL) AS SIN_GEOMETRY_ID,
       COUNT_IF(GEOMETRY_STATUS<>'computed') AS GEOMETRIA_NO_CALCULADA
FROM PROTEIN_AFFINITY.ANALYTICS.OBT_AFFINITY;
