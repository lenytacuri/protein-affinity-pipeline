-- Perfil de los datos ANTES de limpiarlos. Se ejecuta en Snowflake.
-- Los SELECT no actualizan RAW. Las vistas TEMPORARY existen solo en esta sesion.
-- Se incluyen todas las filas measurement_table actualmente cargadas y sus versiones.
-- @section setup
USE WAREHOUSE PPA_WH;
USE DATABASE PROTEIN_AFFINITY;
USE SCHEMA RAW;
CREATE OR REPLACE TEMPORARY VIEW PROFILE_BASE AS
SELECT RECORD_ID, SOURCE_SHA256, PDB_ID, RAW_RECORD:payload AS PAYLOAD,
       RAW_RECORD:source_row::NUMBER AS SOURCE_ROW,
       RAW_RECORD:sheet::VARCHAR AS SOURCE_SHEET,
       IFF(IS_NULL_VALUE(RAW_RECORD:payload:"Source Data Set"),NULL,RAW_RECORD:payload:"Source Data Set"::VARCHAR) AS SOURCE_DATASET,
       IFF(IS_NULL_VALUE(RAW_RECORD:payload:"Complex ID"),NULL,RAW_RECORD:payload:"Complex ID"::VARCHAR) AS COMPLEX_ID,
       IFF(IS_NULL_VALUE(RAW_RECORD:payload:"Mutations"),NULL,RAW_RECORD:payload:"Mutations"::VARCHAR) AS MUTATIONS,
       IFF(IS_NULL_VALUE(RAW_RECORD:payload:"Ligand Chains"),NULL,RAW_RECORD:payload:"Ligand Chains"::VARCHAR) AS LIGAND_CHAINS,
       IFF(IS_NULL_VALUE(RAW_RECORD:payload:"Receptor Chains"),NULL,RAW_RECORD:payload:"Receptor Chains"::VARCHAR) AS RECEPTOR_CHAINS,
       IFF(IS_NULL_VALUE(RAW_RECORD:payload:"KD(M)"),NULL,RAW_RECORD:payload:"KD(M)"::VARCHAR) AS KD_TEXT,
       TRY_TO_DOUBLE(IFF(IS_NULL_VALUE(RAW_RECORD:payload:"KD(M)"),NULL,RAW_RECORD:payload:"KD(M)"::VARCHAR)) AS KD_NUM,
       IFF(IS_NULL_VALUE(RAW_RECORD:payload:"Temperature(K)"),NULL,RAW_RECORD:payload:"Temperature(K)"::VARCHAR) AS TEMPERATURE_TEXT,
       TRY_TO_DOUBLE(IFF(IS_NULL_VALUE(RAW_RECORD:payload:"Temperature(K)"),NULL,RAW_RECORD:payload:"Temperature(K)"::VARCHAR)) AS TEMPERATURE_NUM,
       IFF(IS_NULL_VALUE(RAW_RECORD:payload:"Resolution(Å)"),NULL,RAW_RECORD:payload:"Resolution(Å)"::VARCHAR) AS RESOLUTION_TEXT,
       TRY_TO_DOUBLE(IFF(IS_NULL_VALUE(RAW_RECORD:payload:"Resolution(Å)"),NULL,RAW_RECORD:payload:"Resolution(Å)"::VARCHAR)) AS RESOLUTION_NUM,
       IFF(IS_NULL_VALUE(RAW_RECORD:payload:"Affinity Method"),NULL,RAW_RECORD:payload:"Affinity Method"::VARCHAR) AS AFFINITY_METHOD,
       IFF(IS_NULL_VALUE(RAW_RECORD:payload:"Structure Method"),NULL,RAW_RECORD:payload:"Structure Method"::VARCHAR) AS STRUCTURE_METHOD,
       IFF(IS_NULL_VALUE(RAW_RECORD:payload:"Affinity PubMed ID"),NULL,RAW_RECORD:payload:"Affinity PubMed ID"::VARCHAR) AS AFFINITY_REFERENCE
FROM RAW.SOURCE_RECORDS WHERE INPUT_KIND = 'measurement_table';
CREATE OR REPLACE TEMPORARY VIEW PROFILE_FIELDS AS
WITH fields AS (
 SELECT COLUMN1 AS FIELD FROM VALUES
 ('_unnamed_0'),('Source Data Set'),('Complex ID'),('PDB'),('Mutations'),
 ('Ligand Chains'),('Receptor Chains'),('Ligand Name'),('Receptor Name'),
 ('KD(M)'),('Affinity Method'),('Structure Method'),('Temperature(K)'),
 ('Resolution(Å)'),('PDB PubMed ID'),('PDB Release Date'),
 ('Affinity PubMed ID'),('Affinity Release Date'),('Subgroup')
)
SELECT b.RECORD_ID, f.FIELD, GET(b.PAYLOAD,f.FIELD) AS VALUE
FROM PROFILE_BASE b CROSS JOIN fields f;
-- @section overview
SELECT COUNT(*) AS ROWS_TOTAL, COUNT(DISTINCT RECORD_ID) AS UNIQUE_RECORD_IDS,
 COUNT(DISTINCT PDB_ID) AS UNIQUE_PDB_IDS, COUNT(DISTINCT SOURCE_SHA256) AS SOURCE_VERSIONS,
 COUNT(DISTINCT SOURCE_DATASET) AS SOURCE_DATASETS,
 COUNT(*)-COUNT(DISTINCT RECORD_ID) AS DUPLICATED_TECHNICAL_KEYS,
 COALESCE(COUNT_IF(NOT REGEXP_LIKE(PDB_ID,'([0-9][A-Z0-9]{3}|pdb_[a-z0-9]{8})') OR PDB_ID IS NULL),0) AS INVALID_PDB_FORMAT,
 COALESCE(COUNT_IF(PDB_ID != UPPER(TRIM(PAYLOAD:"PDB"::VARCHAR))),0) AS PDB_INDEX_DIFFERENCES
FROM PROFILE_BASE;
-- @section paper_complex_id_uniqueness
-- El paper deduplica por Complex ID: PDB + cadenas ordenadas + mutaciones + referencia.
-- La misma clave puede reaparecer en otra version de archivo: se comprueba por version.
SELECT SOURCE_SHA256,COUNT(*) AS ROWS_TOTAL,
 COUNT(DISTINCT NULLIF(TRIM(COMPLEX_ID),'')) AS UNIQUE_COMPLEX_IDS,
 COALESCE(COUNT_IF(COMPLEX_ID IS NULL OR TRIM(COMPLEX_ID)=''),0) AS MISSING_COMPLEX_IDS,
 COUNT(NULLIF(TRIM(COMPLEX_ID),''))-COUNT(DISTINCT NULLIF(TRIM(COMPLEX_ID),'')) AS REPEATED_COMPLEX_IDS
FROM PROFILE_BASE GROUP BY SOURCE_SHA256;
-- @section paper_complex_id_duplicates
SELECT SOURCE_SHA256,COMPLEX_ID,COUNT(*) AS N
FROM PROFILE_BASE WHERE COMPLEX_ID IS NOT NULL AND TRIM(COMPLEX_ID)!=''
GROUP BY 1,2 HAVING COUNT(*)>1 ORDER BY N DESC,COMPLEX_ID;
-- @section paper_example_3g6d
SELECT SOURCE_DATASET,COMPLEX_ID,PDB_ID,LIGAND_CHAINS,RECEPTOR_CHAINS,
 MUTATIONS,KD_NUM AS KD_M,AFFINITY_REFERENCE,AFFINITY_METHOD,TEMPERATURE_TEXT
FROM PROFILE_BASE WHERE PDB_ID='3G6D' AND MUTATIONS IS NULL
 AND LIGAND_CHAINS='H, L' AND RECEPTOR_CHAINS='A' AND KD_NUM=1.84e-11
ORDER BY SOURCE_DATASET;
-- @section source_versions
SELECT SOURCE_SHA256, SOURCE_DATASET, COUNT(*) AS ROWS_TOTAL,
 COUNT(DISTINCT PDB_ID) AS UNIQUE_PDB_IDS
FROM PROFILE_BASE GROUP BY 1,2 ORDER BY 1,2;
-- @section completeness
SELECT FIELD, COUNT(*) AS ROWS_TOTAL,
 COALESCE(COUNT_IF(VALUE IS NULL),0) AS ABSENT_KEYS,
 COALESCE(COUNT_IF(IS_NULL_VALUE(VALUE)),0) AS JSON_NULLS,
 COALESCE(COUNT_IF(NOT IS_NULL_VALUE(VALUE) AND TRIM(VALUE::VARCHAR)=''),0) AS BLANK_STRINGS,
 COALESCE(COUNT_IF(VALUE IS NULL OR IS_NULL_VALUE(VALUE) OR TRIM(VALUE::VARCHAR)=''),0) AS MISSING_TOTAL,
 ROUND(100.0*MISSING_TOTAL/NULLIF(COUNT(*),0),2) AS MISSING_PCT,
 COALESCE(COUNT_IF(UPPER(TRIM(VALUE::VARCHAR)) IN ('NA','N/A','?','TBD','NULL','NONE','NAN')),0) AS PLACEHOLDER_TOKENS,
 COUNT(DISTINCT IFF(IS_NULL_VALUE(VALUE),NULL,VALUE::VARCHAR)) AS DISTINCT_NON_NULL,
 COALESCE(COUNT_IF(TYPEOF(VALUE)='VARCHAR' AND VALUE::VARCHAR != TRIM(VALUE::VARCHAR)),0) AS SURROUNDING_SPACES
FROM PROFILE_FIELDS GROUP BY FIELD ORDER BY MISSING_TOTAL DESC,FIELD;
-- @section field_types
SELECT FIELD, TYPEOF(VALUE) AS VALUE_TYPE, COUNT(*) AS N
FROM PROFILE_FIELDS GROUP BY 1,2 ORDER BY 1,3 DESC;
-- @section common_values
SELECT FIELD, IFF(IS_NULL_VALUE(VALUE),'<JSON_NULL>',VALUE::VARCHAR) AS VALUE_TEXT, COUNT(*) AS N
FROM PROFILE_FIELDS GROUP BY 1,2
QUALIFY ROW_NUMBER() OVER(PARTITION BY FIELD ORDER BY N DESC,VALUE_TEXT)<=5
ORDER BY FIELD,N DESC,VALUE_TEXT;
-- @section numeric_validity
SELECT COUNT(*) AS ROWS_TOTAL,
 COALESCE(COUNT_IF(KD_TEXT IS NULL OR TRIM(KD_TEXT)=''),0) AS KD_MISSING,
 COALESCE(COUNT_IF(KD_TEXT IS NOT NULL AND TRIM(KD_TEXT)!='' AND KD_NUM IS NULL),0) AS KD_NOT_NUMERIC,
 COALESCE(COUNT_IF(KD_NUM IS NOT NULL AND NOT (KD_NUM>'-inf'::FLOAT AND KD_NUM<'inf'::FLOAT)),0) AS KD_NONFINITE,
 COALESCE(COUNT_IF(KD_NUM<=0 AND KD_NUM>'-inf'::FLOAT),0) AS KD_NONPOSITIVE,
 COALESCE(COUNT_IF(KD_NUM>0 AND KD_NUM<'inf'::FLOAT),0) AS KD_POSITIVE_FINITE,
 COALESCE(COUNT_IF(TEMPERATURE_TEXT IS NULL OR TRIM(TEMPERATURE_TEXT)=''),0) AS TEMPERATURE_MISSING,
 COALESCE(COUNT_IF(TEMPERATURE_TEXT IS NOT NULL AND TRIM(TEMPERATURE_TEXT)!='' AND TEMPERATURE_NUM IS NULL),0) AS TEMPERATURE_NOT_PLAIN_NUMBER,
 COALESCE(COUNT_IF(TEMPERATURE_TEXT ILIKE '%assum%'),0) AS TEMPERATURE_ASSUMED_LABEL,
 COALESCE(COUNT_IF(TEMPERATURE_NUM<=0),0) AS TEMPERATURE_NONPOSITIVE,
 COALESCE(COUNT_IF(TEMPERATURE_NUM>= 'inf'::FLOAT OR LOWER(TRIM(TEMPERATURE_TEXT)) IN ('nan','-inf','-infinity')),0) AS TEMPERATURE_NONFINITE,
 COALESCE(COUNT_IF(RESOLUTION_TEXT IS NULL OR TRIM(RESOLUTION_TEXT)=''),0) AS RESOLUTION_MISSING,
 COALESCE(COUNT_IF(RESOLUTION_TEXT IS NOT NULL AND TRIM(RESOLUTION_TEXT)!='' AND RESOLUTION_NUM IS NULL),0) AS RESOLUTION_NOT_NUMERIC,
 COALESCE(COUNT_IF(RESOLUTION_NUM<=0),0) AS RESOLUTION_NONPOSITIVE,
 COALESCE(COUNT_IF(RESOLUTION_NUM>='inf'::FLOAT OR LOWER(TRIM(RESOLUTION_TEXT)) IN ('nan','-inf','-infinity')),0) AS RESOLUTION_NONFINITE
FROM PROFILE_BASE;
-- @section numeric_distribution
WITH numbers AS (
 SELECT 'KD(M)' AS FIELD, KD_NUM AS X FROM PROFILE_BASE
 UNION ALL SELECT 'Temperature(K), solo numeros explicitos',TEMPERATURE_NUM FROM PROFILE_BASE
 UNION ALL SELECT 'Resolution(Å)',RESOLUTION_NUM FROM PROFILE_BASE
)
SELECT FIELD,COUNT(*) AS N_FINITE,MIN(X) AS MINIMUM,MAX(X) AS MAXIMUM,AVG(X) AS MEAN,
 STDDEV_SAMP(X) AS STDDEV,MEDIAN(X) AS MEDIAN,
 PERCENTILE_CONT(0.01) WITHIN GROUP(ORDER BY X) AS P01,
 PERCENTILE_CONT(0.25) WITHIN GROUP(ORDER BY X) AS P25,
 PERCENTILE_CONT(0.75) WITHIN GROUP(ORDER BY X) AS P75,
 PERCENTILE_CONT(0.99) WITHIN GROUP(ORDER BY X) AS P99
FROM numbers WHERE X>'-inf'::FLOAT AND X<'inf'::FLOAT GROUP BY FIELD;
-- @section numeric_cases
SELECT RECORD_ID,SOURCE_DATASET,SOURCE_ROW,PDB_ID,KD_TEXT,TEMPERATURE_TEXT,RESOLUTION_TEXT
FROM PROFILE_BASE
WHERE KD_NUM IS NULL OR KD_NUM<=0 OR KD_NUM>='inf'::FLOAT
 OR (TEMPERATURE_TEXT IS NOT NULL AND (TEMPERATURE_NUM IS NULL OR TEMPERATURE_NUM<=0 OR TEMPERATURE_NUM>='inf'::FLOAT))
 OR (RESOLUTION_TEXT IS NOT NULL AND (RESOLUTION_NUM IS NULL OR RESOLUTION_NUM<=0 OR RESOLUTION_NUM>='inf'::FLOAT))
ORDER BY SOURCE_DATASET,SOURCE_ROW;
-- @section temperature_values
SELECT TEMPERATURE_TEXT, COUNT(*) AS N FROM PROFILE_BASE GROUP BY 1 ORDER BY 2 DESC,1;
-- @section affinity_methods
SELECT AFFINITY_METHOD,COUNT(*) AS N FROM PROFILE_BASE GROUP BY 1 ORDER BY 2 DESC,1;
-- @section missing_by_source
SELECT SOURCE_DATASET,COUNT(*) AS ROWS_TOTAL,
 COALESCE(COUNT_IF(KD_TEXT IS NULL OR TRIM(KD_TEXT)=''),0) AS KD_MISSING,
 COALESCE(COUNT_IF(TEMPERATURE_TEXT IS NULL OR TRIM(TEMPERATURE_TEXT)=''),0) AS TEMPERATURE_MISSING,
 COALESCE(COUNT_IF(AFFINITY_METHOD IS NULL OR TRIM(AFFINITY_METHOD)=''),0) AS METHOD_MISSING,
 COALESCE(COUNT_IF(MUTATIONS IS NOT NULL AND TRIM(MUTATIONS)!=''),0) AS MUTATION_ANNOTATED
FROM PROFILE_BASE GROUP BY 1 ORDER BY 1;
-- @section exact_duplicate_groups
-- Igualdad de todos los valores del Excel excepto el indice exportado _unnamed_0.
-- Es evidencia de repeticion, no una orden de borrar observaciones.
SELECT OBJECT_DELETE(PAYLOAD,'_unnamed_0') AS COMPARED_VALUES,
 COUNT(*) AS N,MIN(RECORD_ID) AS EXAMPLE_RECORD_ID,
 LISTAGG(RECORD_ID,',') WITHIN GROUP(ORDER BY RECORD_ID) AS RECORD_IDS
FROM PROFILE_BASE GROUP BY OBJECT_DELETE(PAYLOAD,'_unnamed_0')
HAVING COUNT(*)>1 ORDER BY N DESC,EXAMPLE_RECORD_ID;
-- @section candidate_measurement_groups
-- Candidatos entre fuentes. No prueban que sea el mismo experimento.
-- Se conserva orden/texto de cadenas y mutaciones. Solo se ignoran espacios externos.
SELECT PDB_ID,TRIM(MUTATIONS) AS MUTATIONS_KEY,TRIM(LIGAND_CHAINS) AS LIGAND_KEY,
 TRIM(RECEPTOR_CHAINS) AS RECEPTOR_KEY,TRIM(KD_TEXT) AS KD_KEY,
 TRIM(TEMPERATURE_TEXT) AS TEMPERATURE_KEY,TRIM(AFFINITY_METHOD) AS METHOD_KEY,
 TRIM(AFFINITY_REFERENCE) AS REFERENCE_KEY,COUNT(*) AS N,
 COUNT(DISTINCT SOURCE_DATASET) AS N_SOURCES,
 LISTAGG(DISTINCT SOURCE_DATASET,', ') WITHIN GROUP(ORDER BY SOURCE_DATASET) AS SOURCES,
 MIN(RECORD_ID) AS EXAMPLE_RECORD_ID,
 LISTAGG(RECORD_ID,',') WITHIN GROUP(ORDER BY RECORD_ID) AS RECORD_IDS
FROM PROFILE_BASE GROUP BY 1,2,3,4,5,6,7,8
HAVING COUNT(*)>1 ORDER BY N DESC,EXAMPLE_RECORD_ID;
-- @section broad_candidate_groups
-- Coincidencias al IGNORAR referencia, metodo y temperatura. No es la regla del paper.
-- No eliminar registros por esta agrupacion. Ver paper_complex_id_uniqueness.
-- Nombre tecnico broad_candidate_groups se conserva para continuidad de archivos.
SELECT PDB_ID,TRIM(MUTATIONS) AS MUTATIONS_KEY,TRIM(LIGAND_CHAINS) AS LIGAND_KEY,
 TRIM(RECEPTOR_CHAINS) AS RECEPTOR_KEY,KD_NUM AS KD_M,COUNT(*) AS N,
 COUNT(DISTINCT SOURCE_DATASET) AS N_SOURCES,
 LISTAGG(DISTINCT SOURCE_DATASET,', ') WITHIN GROUP(ORDER BY SOURCE_DATASET) AS SOURCES,
 MIN(RECORD_ID) AS EXAMPLE_RECORD_ID,
 LISTAGG(RECORD_ID,',') WITHIN GROUP(ORDER BY RECORD_ID) AS RECORD_IDS
FROM PROFILE_BASE WHERE KD_NUM>0 AND KD_NUM<'inf'::FLOAT
GROUP BY 1,2,3,4,5 HAVING COUNT(*)>1 ORDER BY N DESC,EXAMPLE_RECORD_ID;
-- @section resource_coverage
-- Se unen por version de fuente y lote. No se mezcla historial de otros Excel.
WITH per_pdb AS (
 SELECT b.SOURCE_SHA256,r.PDB_ID,
 MAX(IFF(r.RESOURCE='structure' AND r.RECEIPT:status::VARCHAR IN ('cached','downloaded') AND f.CONTENT_SHA256 IS NOT NULL,1,0)) AS HAS_STRUCTURE,
 MAX(IFF(r.RESOURCE='entry' AND r.RECEIPT:status::VARCHAR IN ('cached','downloaded') AND e.CONTENT_SHA256 IS NOT NULL,1,0)) AS HAS_METADATA
 FROM RAW.INGESTION_BATCHES b JOIN RAW.BATCH_RESOURCES r ON b.BATCH_ID=r.BATCH_ID
 LEFT JOIN RAW.RESOURCE_FILES f ON f.CONTENT_SHA256=r.RECEIPT:sha256::VARCHAR
 LEFT JOIN RAW.RCSB_ENTRIES e ON e.CONTENT_SHA256=r.RECEIPT:sha256::VARCHAR
 WHERE b.STATUS='LOADED' GROUP BY 1,2
)
SELECT p.PDB_ID,COUNT(*) AS AFFECTED_ROWS,
 MIN(COALESCE(c.HAS_STRUCTURE,0)) AS HAS_STRUCTURE,
 MIN(COALESCE(c.HAS_METADATA,0)) AS HAS_METADATA
FROM PROFILE_BASE p LEFT JOIN per_pdb c ON p.PDB_ID=c.PDB_ID AND p.SOURCE_SHA256=c.SOURCE_SHA256
GROUP BY p.PDB_ID HAVING MIN(COALESCE(c.HAS_STRUCTURE,0))=0 OR MIN(COALESCE(c.HAS_METADATA,0))=0
ORDER BY p.PDB_ID;
-- @section chain_annotations
SELECT COUNT(*) AS ROWS_TOTAL,
 COALESCE(COUNT_IF(LIGAND_CHAINS IS NULL OR TRIM(LIGAND_CHAINS)=''),0) AS LIGAND_MISSING,
 COALESCE(COUNT_IF(RECEPTOR_CHAINS IS NULL OR TRIM(RECEPTOR_CHAINS)=''),0) AS RECEPTOR_MISSING,
 COALESCE(COUNT_IF(CONTAINS(LIGAND_CHAINS,',')),0) AS MULTICHAIN_LIGAND,
 COALESCE(COUNT_IF(CONTAINS(RECEPTOR_CHAINS,',')),0) AS MULTICHAIN_RECEPTOR,
 COALESCE(COUNT_IF(MUTATIONS IS NOT NULL AND TRIM(MUTATIONS)!=''),0) AS MUTATION_ANNOTATED
FROM PROFILE_BASE;
-- @section chain_overlap_cases
WITH chains AS (
 SELECT RECORD_ID,PDB_ID,SOURCE_DATASET,LIGAND_CHAINS,RECEPTOR_CHAINS,
 ARRAY_INTERSECTION(SPLIT(REPLACE(LIGAND_CHAINS,' ',''),','),SPLIT(REPLACE(RECEPTOR_CHAINS,' ',''),',')) AS OVERLAP
 FROM PROFILE_BASE
)
SELECT * FROM chains WHERE ARRAY_SIZE(OVERLAP)>0 ORDER BY RECORD_ID;
-- @section date_formats
SELECT FIELD,COUNT(*) AS ROWS_TOTAL,
 COALESCE(COUNT_IF(VALUE IS NULL OR IS_NULL_VALUE(VALUE) OR TRIM(VALUE::VARCHAR)=''),0) AS MISSING,
 COALESCE(COUNT_IF(REGEXP_LIKE(VALUE::VARCHAR,'[0-9]{4}-[0-9]{2}-[0-9]{2}') AND TRY_TO_DATE(VALUE::VARCHAR,'YYYY-MM-DD') IS NOT NULL),0) AS VALID_ISO_DAY,
 COALESCE(COUNT_IF(REGEXP_LIKE(VALUE::VARCHAR,'[0-9]{4}-[0-9]{2}-[0-9]{2}') AND TRY_TO_DATE(VALUE::VARCHAR,'YYYY-MM-DD') IS NULL),0) AS INVALID_ISO_DAY,
 COALESCE(COUNT_IF(REGEXP_LIKE(VALUE::VARCHAR,'[0-9]{4}')),0) AS YEAR_ONLY,
 COALESCE(COUNT_IF(NOT REGEXP_LIKE(VALUE::VARCHAR,'([0-9]{4}-[0-9]{2}-[0-9]{2}|[0-9]{4})') AND NOT IS_NULL_VALUE(VALUE) AND TRIM(VALUE::VARCHAR)!=''),0) AS OTHER_FORMAT,
 COALESCE(COUNT_IF(REGEXP_LIKE(VALUE::VARCHAR,'[0-9]{4}-[0-9]{2}-[0-9]{2}') AND TRY_TO_DATE(VALUE::VARCHAR,'YYYY-MM-DD')>TO_DATE(CONVERT_TIMEZONE('America/Guayaquil',CURRENT_TIMESTAMP()))),0) AS FUTURE_ISO_DAY
FROM PROFILE_FIELDS WHERE FIELD IN ('PDB Release Date','Affinity Release Date') GROUP BY FIELD;
-- @section reference_formats
SELECT FIELD,COUNT(*) AS ROWS_TOTAL,
 COALESCE(COUNT_IF(VALUE IS NULL OR IS_NULL_VALUE(VALUE) OR TRIM(VALUE::VARCHAR)=''),0) AS MISSING,
 COALESCE(COUNT_IF(REGEXP_LIKE(VALUE::VARCHAR,'[0-9]+')),0) AS SINGLE_NUMERIC_ID,
 COALESCE(COUNT_IF(NOT REGEXP_LIKE(VALUE::VARCHAR,'[0-9]+') AND NOT IS_NULL_VALUE(VALUE) AND TRIM(VALUE::VARCHAR)!=''),0) AS OTHER_REFERENCE_FORMAT
FROM PROFILE_FIELDS WHERE FIELD IN ('PDB PubMed ID','Affinity PubMed ID') GROUP BY FIELD;
-- @section metadata_resolution_comparison
-- Elegimos un JSON por PDB, el mas recientemente recuperado para esta version del Excel.
-- Diferencia no equivale a error: RCSB puede haber revisado la estructura desde el paper.
WITH metadata AS (
 SELECT b.SOURCE_SHA256,r.PDB_ID,e.PAYLOAD,
 ROW_NUMBER() OVER(PARTITION BY b.SOURCE_SHA256,r.PDB_ID
 ORDER BY r.RECEIPT:retrieved_at::TIMESTAMP_TZ DESC,b.BATCH_ID DESC) AS RN
 FROM RAW.INGESTION_BATCHES b JOIN RAW.BATCH_RESOURCES r ON b.BATCH_ID=r.BATCH_ID
 JOIN RAW.RCSB_ENTRIES e ON e.CONTENT_SHA256=r.RECEIPT:sha256::VARCHAR
 WHERE b.STATUS='LOADED' AND r.RESOURCE='entry'
), compared AS (
 SELECT p.RECORD_ID,p.PDB_ID,p.SOURCE_DATASET,p.RESOLUTION_NUM AS EXCEL_RESOLUTION,
 TRY_TO_DOUBLE(m.PAYLOAD:rcsb_entry_info:resolution_combined[0]::VARCHAR) AS RCSB_RESOLUTION
 FROM PROFILE_BASE p JOIN metadata m ON p.PDB_ID=m.PDB_ID AND p.SOURCE_SHA256=m.SOURCE_SHA256 AND m.RN=1
)
SELECT COUNT(*) AS JOINED_ROWS,
 COALESCE(COUNT_IF(EXCEL_RESOLUTION IS NOT NULL AND RCSB_RESOLUTION IS NOT NULL),0) AS COMPARABLE_ROWS,
 COALESCE(COUNT_IF(ABS(EXCEL_RESOLUTION-RCSB_RESOLUTION)>0.01),0) AS DIFFERENT_OVER_001_A,
 COUNT(DISTINCT IFF(ABS(EXCEL_RESOLUTION-RCSB_RESOLUTION)>0.01,PDB_ID,NULL)) AS PDB_WITH_DIFFERENCE
FROM compared;
-- @section metadata_resolution_cases
-- Elegimos un JSON por PDB, el mas recientemente recuperado para esta version del Excel.
-- Diferencia no equivale a error: RCSB puede haber revisado la estructura desde el paper.
WITH metadata AS (
 SELECT b.SOURCE_SHA256,r.PDB_ID,e.PAYLOAD,
 ROW_NUMBER() OVER(PARTITION BY b.SOURCE_SHA256,r.PDB_ID
 ORDER BY r.RECEIPT:retrieved_at::TIMESTAMP_TZ DESC,b.BATCH_ID DESC) AS RN
 FROM RAW.INGESTION_BATCHES b JOIN RAW.BATCH_RESOURCES r ON b.BATCH_ID=r.BATCH_ID
 JOIN RAW.RCSB_ENTRIES e ON e.CONTENT_SHA256=r.RECEIPT:sha256::VARCHAR
 WHERE b.STATUS='LOADED' AND r.RESOURCE='entry'
), compared AS (
 SELECT p.RECORD_ID,p.PDB_ID,p.SOURCE_DATASET,p.RESOLUTION_NUM AS EXCEL_RESOLUTION,
 TRY_TO_DOUBLE(m.PAYLOAD:rcsb_entry_info:resolution_combined[0]::VARCHAR) AS RCSB_RESOLUTION
 FROM PROFILE_BASE p JOIN metadata m ON p.PDB_ID=m.PDB_ID AND p.SOURCE_SHA256=m.SOURCE_SHA256 AND m.RN=1
)
SELECT * FROM compared WHERE ABS(EXCEL_RESOLUTION-RCSB_RESOLUTION)>0.01
ORDER BY PDB_ID,RECORD_ID;
